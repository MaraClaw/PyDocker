import runpy
import sys
from pathlib import Path
from shutil import copytree
from typing import Final

import pytest
from pytest_mock import MockerFixture

from docs import autogen, docs_utils
from pydocker.utils import PROJECT_ROOT

EXAMPLES: Final = (
    "plugins",
    "configs",
    "networks",
    "volumes",
    "images",
    "containers",
    "builders",
    "nodes",
    "services",
)


@pytest.fixture
def docs_root(tmp_path: Path, mocker: MockerFixture) -> Path:
    copytree(PROJECT_ROOT / "docs" / "template", tmp_path / "docs" / "template")
    mocker.patch.object(autogen, "PROJECT_ROOT", tmp_path)
    mocker.patch("pydocker.utils.PROJECT_ROOT", tmp_path)
    mocker.patch.object(docs_utils, "docker", spec_set=())
    mocker.patch("subprocess.run", side_effect=AssertionError("external command"))
    return tmp_path


@pytest.mark.parametrize("api", ["generator", "examples"])
def test_offline_output_is_complete_and_repeatable_when_called_independently(
    api: str, docs_root: Path, mocker: MockerFixture
) -> None:
    providers = [
        mocker.patch.object(
            docs_utils,
            f"generate_code_demo_{example}",
            side_effect=AssertionError("live provider dispatched"),
        )
        for example in EXAMPLES
    ]
    destination = docs_root / "docs" / "generated_sources"
    if api == "examples":
        autogen.md_generate(autogen.pages, docs_root / "docs" / "template", destination)

    outputs = []
    for _ in range(2):
        if api == "generator":
            autogen.mkdoc_autogen()
        else:
            docs_utils.add_all_code_examples(destination)
        outputs.append(
            {
                str(path.relative_to(destination)): path.read_bytes()
                for path in destination.rglob("*.md")
            }
        )

    assert outputs[0] == outputs[1]
    assert set(outputs[0]) == set(autogen.pages)
    for page, data in outputs[0].items():
        assert b"@INSERT_GENERATED_CODE@" not in data
        assert b"{{autogenerated}}" not in data
        for module in autogen.pages[page]:
            assert f"## ::: {module}".encode() in data
    for example in EXAMPLES:
        template = (
            docs_root / "docs" / "template" / "objects" / f"{example}.md"
        ).read_text()
        prefix, suffix = template.split("@INSERT_GENERATED_CODE@")
        rendered = (destination / "objects" / f"{example}.md").read_text()
        if api == "generator":
            prefix, suffix = docs_utils.add_links(prefix), docs_utils.add_links(suffix)
        assert rendered.startswith(prefix)
        insertion = rendered[len(prefix) : rendered.index("```", len(prefix))]
        assert insertion.startswith("#")
        assert "--live-examples" in insertion
        assert "type =" not in insertion
        assert suffix.split("{{autogenerated}}")[0] in rendered
    for provider in providers:
        provider.assert_not_called()


@pytest.mark.parametrize("api", ["generator", "examples", "cli"])
def test_live_providers_render_their_output_when_explicitly_requested(
    api: str, docs_root: Path, mocker: MockerFixture
) -> None:
    providers = {
        example: mocker.patch.object(
            docs_utils, f"generate_code_demo_{example}", return_value=f"live-{example}"
        )
        for example in EXAMPLES
    }
    destination = docs_root / "docs" / "generated_sources"
    if api == "examples":
        autogen.md_generate(autogen.pages, docs_root / "docs" / "template", destination)

    if api == "generator":
        autogen.mkdoc_autogen(live_examples=True)
    elif api == "examples":
        docs_utils.add_all_code_examples(destination, live_examples=True)
    else:
        mocker.patch("sys.argv", ["docs.autogen", "--live-examples"])
        mocker.patch.dict(sys.modules)
        del sys.modules["docs.autogen"]
        runpy.run_module("docs.autogen", run_name="__main__")

    for example, provider in providers.items():
        provider.assert_called_once_with()
        assert (
            f"live-{example}" in (destination / "objects" / f"{example}.md").read_text()
        )


def test_generation_propagates_failure_when_live_provider_fails(
    docs_root: Path, mocker: MockerFixture
) -> None:
    mocker.patch.object(
        docs_utils, "generate_code_demo_plugins", side_effect=LookupError
    )
    later_provider = mocker.patch.object(docs_utils, "generate_code_demo_configs")

    with pytest.raises(LookupError):
        autogen.mkdoc_autogen(live_examples=True)

    later_provider.assert_not_called()
