"""Offline generation and staged-publication contracts with mocked live providers.

Templates and generated output live under a temporary project root. External
commands and real Docker access are rejected by the fixture.
"""

import runpy
import sys
from pathlib import Path
from shutil import copytree
from typing import Final

import pytest
from pytest_mock import MockerFixture

from docs import autogen, docs_utils
from pywhales.utils import PROJECT_ROOT

EXAMPLES: Final = (
    "plugins",
    "configs",
    "networks",
    "volumes",
    "images",
    "containers",
    "builders",
    "nodes",
    "services",
)


@pytest.fixture
def docs_root(tmp_path: Path, mocker: MockerFixture) -> Path:
    """Copy templates into a temporary project and reject external operations.

    Args:
        tmp_path: Per-test project root owned by pytest.
        mocker: Redirects generator paths and disables real Docker/subprocess use.

    Returns:
        The root containing the copied docs/template tree.
    """
    copytree(PROJECT_ROOT / "docs" / "template", tmp_path / "docs" / "template")
    mocker.patch.object(autogen, "PROJECT_ROOT", tmp_path)
    mocker.patch("pywhales.utils.PROJECT_ROOT", tmp_path)
    mocker.patch.object(docs_utils, "docker", spec_set=())
    mocker.patch("subprocess.run", side_effect=AssertionError("external command"))
    return tmp_path


def snapshot_tree(root: Path) -> list[tuple[Path, bytes | None]]:
    """Return sorted relative paths with file bytes or None for directories."""
    return [
        (path.relative_to(root), path.read_bytes() if path.is_file() else None)
        for path in sorted(root.rglob("*"))
    ]


@pytest.mark.parametrize("api", ["generator", "examples"])
def test_offline_output_is_complete_and_repeatable_when_called_independently(
    api: str, docs_root: Path, mocker: MockerFixture
) -> None:
    providers = [
        mocker.patch.object(
            docs_utils,
            f"generate_code_demo_{example}",
            side_effect=AssertionError("live provider dispatched"),
        )
        for example in EXAMPLES
    ]
    destination = docs_root / "docs" / "generated_sources"
    if api == "examples":
        autogen.md_generate(autogen.pages, docs_root / "docs" / "template", destination)

    outputs = []
    for _ in range(2):
        if api == "generator":
            autogen.mkdoc_autogen()
        else:
            docs_utils.add_all_code_examples(destination)
        outputs.append(
            {
                str(path.relative_to(destination)): path.read_bytes()
                for path in destination.rglob("*.md")
            }
        )

    assert outputs[0] == outputs[1]
    assert set(outputs[0]) == set(autogen.pages)
    for page, data in outputs[0].items():
        assert b"@INSERT_GENERATED_CODE@" not in data
        assert b"{{autogenerated}}" not in data
        for module in autogen.pages[page]:
            assert f"## ::: {module}".encode() in data
    for example in EXAMPLES:
        template = (
            docs_root / "docs" / "template" / "objects" / f"{example}.md"
        ).read_text()
        prefix, suffix = template.split("@INSERT_GENERATED_CODE@")
        rendered = (destination / "objects" / f"{example}.md").read_text()
        if api == "generator":
            prefix, suffix = docs_utils.add_links(prefix), docs_utils.add_links(suffix)
        assert rendered.startswith(prefix)
        insertion = rendered[len(prefix) : rendered.index("```", len(prefix))]
        assert insertion.startswith("#")
        assert "--live-examples" in insertion
        assert "type =" not in insertion
        assert suffix.split("{{autogenerated}}")[0] in rendered
    for provider in providers:
        provider.assert_not_called()
    assert set((docs_root / "docs").iterdir()) == {
        docs_root / "docs" / "template",
        destination,
    }


def test_generator_removes_stale_entries_when_replacing_existing_tree(
    docs_root: Path,
) -> None:
    destination = docs_root / "docs" / "generated_sources"
    autogen.mkdoc_autogen()
    expected = snapshot_tree(destination)
    (destination / "index.md").write_bytes(b"previous index")
    (destination / "obsolete" / "empty").mkdir(parents=True)
    (destination / "obsolete" / "old.md").write_bytes(b"stale page")
    (destination / "obsolete.bin").write_bytes(b"\x00\xff")

    autogen.mkdoc_autogen()

    assert snapshot_tree(destination) == expected
    assert set((docs_root / "docs").iterdir()) == {
        docs_root / "docs" / "template",
        destination,
    }


def test_generator_preserves_guide_body_when_template_name_differs(
    docs_root: Path,
) -> None:
    template = (
        docs_root / "docs/template/user_guide/running_pydocker_inside_a_container.md"
    ).read_text(encoding="utf-8")

    autogen.mkdoc_autogen()

    rendered = (
        docs_root
        / "docs/generated_sources/user_guide/running_pywhales_inside_a_container.md"
    ).read_text(encoding="utf-8")
    assert rendered == docs_utils.add_links(template)


def test_generator_renders_api_when_template_is_intentionally_absent(
    docs_root: Path,
) -> None:
    template = docs_root / "docs/template/sub-commands/context.md"
    template.unlink(missing_ok=True)

    autogen.mkdoc_autogen()

    rendered = (docs_root / "docs/generated_sources/sub-commands/context.md").read_text(
        encoding="utf-8"
    )
    assert (
        rendered.strip() == "## ::: pywhales.components.context.cli_wrapper.ContextCLI"
    )


@pytest.mark.parametrize("api", ["generator", "examples", "cli"])
def test_live_providers_render_their_output_when_explicitly_requested(
    api: str, docs_root: Path, mocker: MockerFixture
) -> None:
    providers = {
        example: mocker.patch.object(
            docs_utils, f"generate_code_demo_{example}", return_value=f"live-{example}"
        )
        for example in EXAMPLES
    }
    destination = docs_root / "docs" / "generated_sources"
    if api == "examples":
        autogen.md_generate(autogen.pages, docs_root / "docs" / "template", destination)

    if api == "generator":
        autogen.mkdoc_autogen(live_examples=True)
    elif api == "examples":
        docs_utils.add_all_code_examples(destination, live_examples=True)
    else:
        mocker.patch("sys.argv", ["docs.autogen", "--live-examples"])
        mocker.patch.dict(sys.modules)
        del sys.modules["docs.autogen"]
        runpy.run_module("docs.autogen", run_name="__main__")

    for example, provider in providers.items():
        provider.assert_called_once_with()
        assert (
            f"live-{example}" in (destination / "objects" / f"{example}.md").read_text()
        )


@pytest.mark.parametrize("published", [False, True])
def test_generation_preserves_previous_tree_when_live_provider_fails(
    published: bool, docs_root: Path, mocker: MockerFixture
) -> None:
    if published:
        autogen.mkdoc_autogen()
        (docs_root / "docs/generated_sources/retired.bin").write_bytes(b"\x00\xff")
    previous = snapshot_tree(docs_root / "docs")
    first_provider = mocker.patch.object(
        docs_utils, "generate_code_demo_plugins", return_value="live-plugins"
    )
    mocker.patch.object(
        docs_utils, "generate_code_demo_configs", side_effect=LookupError
    )
    later_provider = mocker.patch.object(docs_utils, "generate_code_demo_networks")

    with pytest.raises(LookupError):
        autogen.mkdoc_autogen(live_examples=True)

    assert snapshot_tree(docs_root / "docs") == previous
    first_provider.assert_called_once_with()
    later_provider.assert_not_called()


@pytest.mark.parametrize("published", [False, True])
def test_generation_preserves_previous_tree_when_template_rendering_fails(
    published: bool, docs_root: Path
) -> None:
    if published:
        autogen.mkdoc_autogen()
        (docs_root / "docs/generated_sources/retired.bin").write_bytes(b"\x00\xff")
    (docs_root / "docs/template/index.md").write_bytes(b"\xff")
    previous = snapshot_tree(docs_root / "docs")

    with pytest.raises(UnicodeDecodeError):
        autogen.mkdoc_autogen()

    assert snapshot_tree(docs_root / "docs") == previous
